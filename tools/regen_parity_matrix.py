"""Render the CLI -> API -> UI parity matrix from the capability catalogue plus `parity-ui.json`.

Run from the repository root: `uv run python tools/regen_parity_matrix.py`.

The catalogue owns route, status, slice and scopes (and the reason of an excluded row). The hand-curated
half, the UI route/action and the automated proof references, lives in `docs/review-studio/parity-ui.json`
keyed by CLI command; `tests/architecture/test_cli_api_ui_parity.py` checks that every reference resolves
and that the committed Markdown equals `render()`.
"""

import json
import pathlib

from docs.api.openapi import build_capability_catalog

ROOT = pathlib.Path(__file__).resolve().parents[1]
MATRIX = ROOT / "docs/review-studio/cli-api-ui-parity.md"
UI_DATA = ROOT / "docs/review-studio/parity-ui.json"

PREAMBLE = """# Review Studio CLI → API → UI parity matrix

Generated by `tools/regen_parity_matrix.py` from the capability catalogue (`build_capability_catalog`) and
`docs/review-studio/parity-ui.json`; edit those, never this table. Each row links one CLI command, one API
operation, one UI route/action, its owning slice and automated proof. A capability is `available` only when
an equivalent X20 HTTP operation exists; `excluded` rows carry the reason they stay CLI-only.

`Pending UI (Sx.y)` marks an available operation whose screen is still being built; the allow-list lives in
`tests/architecture/test_cli_api_ui_parity.py` and must be empty before release. Proof entries are
`file::test_name` (API) or `file › test title` (frontend unit test or Playwright E2E).

"""
HEADER = "| CLI command | API operation | API status | UI route › action | Owning slice | Required scopes | Proof |"


def _row(capability: dict, ui: dict) -> str:
    command = capability["cli_command"]
    route = f'`{capability["route"]}`' if capability["route"] else "—"
    scopes = ", ".join(f"`{s}`" for s in capability["scopes"]) or "—"
    if capability["status"] == "excluded":
        cell, proof = f"Excluded (CLI only): {capability['reason']}", "—"
    else:
        entry = ui[command]
        if entry.get("pending"):
            cell = f"Pending UI ({entry['pending']})"
        else:
            where, _, action = entry["ui"].partition(" › ")
            cell = f"`{where}` › {action}"
        parts = [f"API: `{ref}`" for ref in entry.get("api", [])] + [f"UI: `{ref}`" for ref in entry.get("proof", [])]
        proof = "<br>".join(parts) or "—"
    return f'| `docs {command}` | {route} | {capability["status"]} | {cell} | {capability["slice"]} | {scopes} | {proof} |'


def render() -> str:
    ui = json.loads(UI_DATA.read_text(encoding="utf-8"))
    rows = [_row(c, ui) for g in build_capability_catalog()["groups"] for c in g["capabilities"]]
    return PREAMBLE + "\n".join([HEADER, "|" + " --- |" * 7, *rows]) + "\n"


if __name__ == "__main__":
    text = render()
    MATRIX.write_text(text, encoding="utf-8", newline="\n")
    print(text.count("\n| `docs "), "rows")
